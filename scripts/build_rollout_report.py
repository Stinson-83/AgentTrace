#!/usr/bin/env python3
"""Assemble reports/ROLLOUT_ANALYSIS.md from reports/rollout_narrative.md (hand-written) plus one
generated section per recorded rollout under results/<env>/rollout*/ (via analyze_rollout.py)."""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parts = [(ROOT / "reports" / "rollout_narrative.md").read_text() if (ROOT / "reports" / "rollout_narrative.md").exists() else "# ROLLOUT_ANALYSIS.md\n"]
    parts.append("\n---\n\n# Recorded runs (generated by scripts/analyze_rollout.py)\n")
    for env in sorted(p.name for p in (ROOT / "environments").iterdir() if (p / "task.toml").exists()):
        for run in sorted(p.name for p in (ROOT / "results" / env).glob("rollout*")) if (ROOT / "results" / env).exists() else []:
            out = subprocess.run([sys.executable, str(ROOT / "scripts" / "analyze_rollout.py"), env, "--variant", run, "--diff-lines", "120"],
                                 capture_output=True, text=True, cwd=ROOT)
            parts.append("\n" + (out.stdout or out.stderr))
    (ROOT / "reports" / "ROLLOUT_ANALYSIS.md").write_text("\n".join(parts))
    print("wrote reports/ROLLOUT_ANALYSIS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
